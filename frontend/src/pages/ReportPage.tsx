import { useState } from 'react';
import { motion } from 'framer-motion';
import { FileText, Download, FileSpreadsheet, AlertTriangle, CheckCircle2, User, ListOrdered } from 'lucide-react';
import { useApp } from '../store/AppContext';
import jsPDF from 'jspdf';

function downloadCSV(rows: string[][], filename: string) {
  const content = rows.map(r => r.map(cell => `"${String(cell).replace(/"/g, '""')}"`).join(',')).join('\n');
  const blob = new Blob([content], { type: 'text/csv' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url; a.download = filename; a.click();
  URL.revokeObjectURL(url);
}

export default function ReportPage() {
  const { state } = useApp();
  const { profile, preferenceList, auditReport } = state;
  const [isGenerating, setIsGenerating] = useState(false);
  const [generated, setGenerated] = useState(false);

  const items = preferenceList.items;
  const now = new Date().toLocaleString('en-IN', { dateStyle: 'long', timeStyle: 'short' });

  const DISCLAIMER = `This report is a personal decision-support document generated by JOSAA MATE AI, an independent platform not affiliated with JoSAA, JAB, IITs, NITs, IIITs or any government body. It does not constitute official JoSAA allotment results. All cutoff data shown is illustrative demo data only. Verify all information at josaa.nic.in before making decisions.`;

  async function handleGeneratePDF() {
    setIsGenerating(true);
    await new Promise(r => setTimeout(r, 1200));

    const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
    const W = 210; const margin = 18;
    let y = margin;

    const addText = (text: string, x: number, yPos: number, opts: Record<string, unknown> = {}) => {
      doc.text(text, x, yPos, opts);
    };
    const line = () => { doc.setDrawColor(220, 220, 220); doc.line(margin, y, W - margin, y); y += 5; };

    // --- Cover Page ---
    doc.setFillColor(16, 24, 40);
    doc.rect(0, 0, W, 297, 'F');

    doc.setTextColor(255, 255, 255);
    doc.setFontSize(28); doc.setFont('helvetica', 'bold');
    addText('JOSAA MATE AI', margin, 60);
    doc.setFontSize(13); doc.setFont('helvetica', 'normal');
    doc.setTextColor(180, 170, 255);
    addText('Your Rank. Your Choices. Your Future.', margin, 72);

    doc.setFontSize(18); doc.setTextColor(255, 255, 255); doc.setFont('helvetica', 'bold');
    addText('Counselling Decision-Support Report', margin, 95);

    doc.setFontSize(10); doc.setFont('helvetica', 'normal'); doc.setTextColor(160, 160, 180);
    addText(`Generated: ${now}`, margin, 108);
    if (profile?.name) addText(`Student: ${profile.name}`, margin, 116);

    doc.setFontSize(8); doc.setTextColor(120, 120, 140);
    const dlines = doc.splitTextToSize(DISCLAIMER, W - margin * 2);
    doc.text(dlines, margin, 265);

    // --- Profile Page ---
    doc.addPage();
    doc.setTextColor(16, 24, 40); y = margin;

    doc.setFontSize(16); doc.setFont('helvetica', 'bold');
    addText('Student Profile Summary', margin, y); y += 8; line();

    doc.setFontSize(10); doc.setFont('helvetica', 'normal');
    const pRows = [
      ['Name', profile?.name || 'Not provided'],
      ['JEE Main CRL', profile?.jeemainCRL?.toString() || 'Not set'],
      ['JEE Advanced Rank', profile?.jeeAdvancedRank?.toString() || 'Not set'],
      ['Category', profile?.category || 'Not set'],
      ['PwD', profile?.isPwD ? 'Yes' : 'No'],
      ['Gender', profile?.gender || 'Not set'],
      ['Home State', profile?.homeState || 'Not set'],
      ['Nationality', profile?.nationality || 'Not set'],
      ['JEE Advanced Qualified', profile?.jeeAdvancedQualified ? 'Yes' : 'No'],
    ];
    pRows.forEach(([k, v]) => {
      doc.setFont('helvetica', 'bold'); addText(k + ':', margin, y);
      doc.setFont('helvetica', 'normal'); addText(v, margin + 55, y);
      y += 7;
    });

    // --- Preference List Page ---
    doc.addPage(); y = margin;
    doc.setFontSize(16); doc.setFont('helvetica', 'bold'); doc.setTextColor(16, 24, 40);
    addText('My Preference List', margin, y); y += 4;
    doc.setFontSize(8); doc.setFont('helvetica', 'italic'); doc.setTextColor(120, 120, 140);
    addText('⚠ All closing ranks shown are DEMO DATA only and do not represent official JoSAA data.', margin, y + 4); y += 10;
    line();

    if (items.length === 0) {
      doc.setFontSize(10); doc.setFont('helvetica', 'normal'); doc.setTextColor(120, 120, 140);
      addText('No preferences added yet.', margin, y);
    } else {
      items.forEach((item, i) => {
        if (y > 270) { doc.addPage(); y = margin; }
        doc.setFontSize(10); doc.setFont('helvetica', 'bold'); doc.setTextColor(16, 24, 40);
        addText(`${i + 1}. ${item.instituteName}`, margin, y); y += 5;
        doc.setFont('helvetica', 'normal'); doc.setFontSize(9); doc.setTextColor(80, 80, 100);
        addText(`   ${item.programName} | ${item.seatPool} | ${item.quota}${item.closingRank2024 ? ` | Closing Rank 2024 (Demo): ${item.closingRank2024}` : ''}`, margin, y);
        y += 7;
      });
    }

    // --- Audit Page ---
    if (auditReport) {
      doc.addPage(); y = margin;
      doc.setFontSize(16); doc.setFont('helvetica', 'bold'); doc.setTextColor(16, 24, 40);
      addText('Audit Results', margin, y); y += 8; line();
      doc.setFontSize(10); doc.setFont('helvetica', 'normal');
      addText(`Audit Score: ${auditReport.auditCompletion}/100`, margin, y); y += 6;
      addText(`Total Preferences: ${auditReport.totalPreferences}`, margin, y); y += 6;
      addText(`Warnings: ${auditReport.warnings.length}`, margin, y); y += 10;
      auditReport.warnings.forEach((w, i) => {
        if (y > 265) { doc.addPage(); y = margin; }
        doc.setFont('helvetica', 'bold');
        addText(`${i + 1}. [${w.severity.toUpperCase()}] ${w.title}`, margin, y); y += 5;
        doc.setFont('helvetica', 'normal'); doc.setTextColor(80, 80, 100);
        const lines2 = doc.splitTextToSize(w.description, W - margin * 2 - 5);
        doc.text(lines2, margin + 4, y); y += lines2.length * 4 + 3;
        doc.setTextColor(16, 24, 40);
      });
    }

    // --- Final disclaimer page ---
    doc.addPage(); y = margin;
    doc.setFontSize(14); doc.setFont('helvetica', 'bold'); doc.setTextColor(16, 24, 40);
    addText('Important Disclaimer', margin, y); y += 8; line();
    doc.setFontSize(9); doc.setFont('helvetica', 'normal'); doc.setTextColor(80, 80, 100);
    const dText = doc.splitTextToSize(DISCLAIMER, W - margin * 2);
    doc.text(dText, margin, y); y += dText.length * 5 + 8;
    doc.setFontSize(9); doc.setTextColor(100, 100, 120);
    addText('Data Sources:', margin, y); y += 5;
    ['JoSAA Official: josaa.nic.in', 'Opening/Closing Ranks: josaa.nic.in/or-cr/', 'JEE Advanced: jeeadv.ac.in', 'JEE Main: jeemain.nta.nic.in']
      .forEach(s => { addText('• ' + s, margin + 4, y); y += 5; });

    doc.save('JOSAA_MATE_AI_Report.pdf');
    setIsGenerating(false);
    setGenerated(true);
  }

  function handleDownloadCSV() {
    const rows: string[][] = [
      ['JOSAA MATE AI – My Preference List'],
      [`Generated: ${now}`],
      ['[DEMO DATA – All ranks are illustrative only]'],
      [],
      ['Order', 'Institute', 'Programme', 'Type', 'Seat Pool', 'Quota', 'Gender Pool', 'Closing Rank 2024 (Demo)', 'Notes'],
      ...items.map((item, i) => [
        String(i + 1), item.instituteName, item.programName,
        item.instituteType, item.seatPool, item.quota, item.genderPool,
        item.closingRank2024?.toString() ?? 'N/A', item.notes ?? '',
      ]),
      [],
      [DISCLAIMER],
    ];
    downloadCSV(rows, 'JOSAA_MATE_Preferences.csv');
  }

  const sections = [
    { icon: User, label: 'Student Profile Summary', done: !!profile?.name },
    { icon: CheckCircle2, label: 'Eligibility Results', done: !!profile?.category },
    { icon: ListOrdered, label: 'Complete Preference List', done: items.length > 0 },
    { icon: AlertTriangle, label: 'Audit Results', done: !!auditReport },
    { icon: FileText, label: 'Data Sources & Disclaimers', done: true },
  ];

  return (
    <div className="space-y-6 max-w-3xl mx-auto">
      <div>
        <div className="flex items-center gap-2 mb-1">
          <FileText size={22} className="text-indigo-600" />
          <h1 className="section-heading">Final Counselling Report</h1>
        </div>
        <p className="section-subheading">Generate and download your personalised counselling decision-support report.</p>
      </div>

      {/* Disclaimer */}
      <div className="card p-4 bg-amber-50 border border-amber-200 flex items-start gap-2 text-sm text-amber-800">
        <AlertTriangle size={15} className="shrink-0 mt-0.5" />
        <span>{DISCLAIMER}</span>
      </div>

      {/* Preview */}
      <div className="card p-6 space-y-4">
        <h2 className="font-semibold text-gray-800">Report Contents Preview</h2>
        <div className="space-y-2">
          {sections.map(s => (
            <div key={s.label} className="flex items-center gap-3 py-2 border-b border-gray-50 last:border-0">
              <div className={`p-1.5 rounded-lg ${s.done ? 'bg-green-50' : 'bg-gray-50'}`}>
                <s.icon size={14} className={s.done ? 'text-green-600' : 'text-gray-400'} />
              </div>
              <span className="text-sm text-gray-700 flex-1">{s.label}</span>
              <span className={`text-xs font-medium ${s.done ? 'text-green-600' : 'text-gray-400'}`}>
                {s.done ? '✓ Ready' : 'Not available'}
              </span>
            </div>
          ))}
        </div>
        <p className="text-xs text-gray-400">
          Preferences in list: <strong>{items.length}</strong> &nbsp;|&nbsp;
          Audit warnings: <strong>{auditReport?.warnings.length ?? 'Not run'}</strong>
        </p>
      </div>

      {/* Download actions */}
      <div className="card p-6">
        <h2 className="font-semibold text-gray-800 mb-4">Download Report</h2>
        <div className="grid sm:grid-cols-2 gap-3">
          <motion.button whileHover={{ scale: 1.02 }} whileTap={{ scale: 0.98 }}
            onClick={handleGeneratePDF} disabled={isGenerating}
            className="btn-primary justify-center py-3 text-sm disabled:opacity-60">
            {isGenerating ? <><FileText size={16} className="animate-pulse" /> Generating…</> : <><Download size={16} /> Download PDF Report</>}
          </motion.button>
          <motion.button whileHover={{ scale: 1.02 }} whileTap={{ scale: 0.98 }}
            onClick={handleDownloadCSV} className="btn-outline justify-center py-3 text-sm">
            <FileSpreadsheet size={16} /> Download CSV / Excel
          </motion.button>
        </div>
        {generated && (
          <motion.div initial={{ opacity: 0, y: 4 }} animate={{ opacity: 1, y: 0 }}
            className="mt-4 p-3 bg-green-50 border border-green-200 rounded-xl text-sm text-green-700 flex items-center gap-2">
            <CheckCircle2 size={15} /> PDF downloaded successfully!
          </motion.div>
        )}
      </div>
    </div>
  );
}
